import express from 'express';
import 'dotenv/config';
import { createClient } from '@supabase/supabase-js';
import { createApp } from './backend.js';
const supabaseUrl=process.env.SUPABASE_URL;
const serviceKey=process.env.SUPABASE_SERVICE_ROLE_KEY;
const store=supabaseUrl&&serviceKey?createClient(supabaseUrl,serviceKey,{auth:{persistSession:false,autoRefreshToken:false}}):undefined;
const app=createApp({app:express(),store,adminIds:(process.env.ADMIN_USER_IDS||'').split(',').map(x=>x.trim()).filter(Boolean),publicConfig:{supabaseUrl,supabaseAnonKey:process.env.SUPABASE_ANON_KEY}});
if(!process.env.VERCEL)app.listen(process.env.PORT||3000,()=>console.log(`AgroCare AI: http://localhost:${process.env.PORT||3000}`));
export default app;
